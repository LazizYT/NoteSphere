export function t(lang: Language, key: keyof typeof TRANSLATIONS['ru']): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['ru'][key] || key;
}

export function formatCurrency(amount: number, currency: 'sum' | 'dollar' | 'krw' | 'rub' = 'sum'): string {
  const formatted = Math.abs(amount).toLocaleString('ru-RU');
  const sign = amount < 0 ? '-' : amount > 0 ? '+' : '';
  switch (currency) {
    case 'dollar':
      return `${sign}$ ${formatted}`;
    case 'krw':
      return `${sign}₩ ${formatted}`;
    case 'rub':
      return `${sign}${formatted} ₽`;
    case 'sum':
    default:
      return `${sign}${formatted} сум`;
  }
}
